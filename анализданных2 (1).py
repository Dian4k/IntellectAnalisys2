import matplotlib.pyplot as plt

def is_leaf(node):
    return "feature" not in node


def draw_limited_tree(ax, node, x, y, dx, level, max_depth):
    if level > max_depth:
        ax.text(x, y, "...", ha="center", va="center", bbox=dict(boxstyle="round", fc="white"))
        return

    if is_leaf(node):
        ax.text(x, y, node["prediction"], ha="center", va="center", bbox=dict(boxstyle="round", fc="lightgreen"))
        return

    if node["type"] == "numeric":
        label = f'{node["feature"]}\n<= {node["threshold"]:.2f}'
        ax.text(x, y, label, ha="center", va="center", bbox=dict(boxstyle="round", fc="lightblue"))

        child_y = y - 2
        left_x = x - dx
        right_x = x + dx

        ax.plot([x, left_x], [y, child_y], "k-")
        ax.plot([x, right_x], [y, child_y], "k-")

        ax.text((x + left_x) / 2, (y + child_y) / 2, "<=", ha="center", va="center")
        ax.text((x + right_x) / 2, (y + child_y) / 2, ">", ha="center", va="center")

        draw_limited_tree(ax, node["left"], left_x, child_y, dx / 1.8, level + 1, max_depth)
        draw_limited_tree(ax, node["right"], right_x, child_y, dx / 1.8, level + 1, max_depth)

    else:
        ax.text(x, y, node["feature"], ha="center", va="center", bbox=dict(boxstyle="round", fc="lightblue"))

        children = list(node["children"].items())
        n = len(children)
        child_y = y - 2

        for i, (value, child) in enumerate(children):
            child_x = x + (i - (n - 1) / 2) * dx
            ax.plot([x, child_x], [y, child_y], "k-")
            ax.text((x + child_x) / 2, (y + child_y) / 2, str(value), ha="center", va="center")
            draw_limited_tree(ax, child, child_x, child_y, dx / max(n, 2), level + 1, max_depth)


def visualize_tree(model, title, max_depth=5):
    plt.figure(figsize=(20, 10))
    ax = plt.gca()
    ax.set_title(title)
    ax.axis("off")

    draw_limited_tree(ax, model.tree, x=0, y=0, dx=8, level=1, max_depth=max_depth)

    plt.show()

