import numpy as np
import pandas as pd
from collections import Counter
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score

class DecisionTree:
    def __init__(self, criterion="information_gain"):
        if criterion not in ("information_gain", "gain_ratio", "gini_index"):
            raise ValueError("Неизвестный критерий")

        self.criterion = criterion
        self.tree = None

    def _entropy(self, counts):
        counts = np.array(counts, dtype=float)
        p = counts / counts.sum()

        return -np.sum(p[p > 0] * np.log2(p[p > 0]))

    def _gini(self, counts):
        counts = np.array(counts, dtype=float)
        p = counts / counts.sum()

        return 1 - np.sum(p ** 2)

    def _score(self, groups):
        groups = np.array(groups)
        sizes = groups.sum(axis=1)
        total = sizes.sum()
        parent = groups.sum(axis=0)

        if self.criterion == "gini_index":
            parent_impurity = self._gini(parent)
            children_impurity = sum((sizes[i] / total) * self._gini(groups[i]) for i in range(len(groups)))

            return parent_impurity - children_impurity

        parent_entropy = self._entropy(parent)
        children_entropy = sum((sizes[i] / total) * self._entropy(groups[i]) for i in range(len(groups)))
        information_gain = parent_entropy - children_entropy

        if self.criterion == "information_gain":
            return information_gain

        split_info = self._entropy(sizes)

        if split_info == 0:
            return 0

        return information_gain / split_info

    def _best_split(self, X, y, features):
        best = None
        best_score = -1

        for feature in features:
            column = X[feature].to_numpy()

            if np.issubdtype(X[feature].dtype, np.number):
                order = np.argsort(column)
                x_sorted = column[order]
                y_sorted = y[order]

                positive = (y_sorted == ">50K").astype(int)
                positive_left = np.cumsum(positive)

                for i in range(len(y) - 1):
                    if x_sorted[i] == x_sorted[i + 1]:
                        continue

                    left_size = i + 1
                    right_size = len(y) - left_size

                    left_positive = positive_left[i]
                    right_positive = positive_left[-1] - left_positive

                    groups = [
                        [left_size - left_positive, left_positive],
                        [right_size - right_positive, right_positive]
                    ]

                    score = self._score(groups)

                    if score > best_score:
                        best_score = score
                        threshold = (x_sorted[i] + x_sorted[i + 1]) / 2
                        best = {"feature": feature, "type": "numeric", "threshold": threshold, "score": score}

            else:
                values = np.unique(column)

                if len(values) <= 1:
                    continue

                groups = []

                for value in values:
                    subset = y[column == value]
                    negative = np.sum(subset == "<=50K")
                    positive = np.sum(subset == ">50K")
                    groups.append([negative, positive])

                score = self._score(groups)

                if score > best_score:
                    best_score = score
                    best = {"feature": feature, "type": "categorical", "score": score}

        return best

    def _build(self, X, y, features):
        positive = np.sum(y == ">50K")
        negative = np.sum(y == "<=50K")
        prediction = ">50K" if positive > negative else "<=50K"

        node = {"prediction": prediction}

        if positive == 0 or negative == 0 or len(features) == 0:
            return node

        split = self._best_split(X, y, features)

        if split is None or split["score"] <= 0:
            return node

        feature = split["feature"]

        node["feature"] = feature
        node["type"] = split["type"]

        if split["type"] == "numeric":
            threshold = split["threshold"]
            mask = X[feature].to_numpy() <= threshold

            node["threshold"] = threshold
            node["left"] = self._build(X[mask], y[mask], features)
            node["right"] = self._build(X[~mask], y[~mask], features)

        else:
            node["children"] = {}
            new_features = [f for f in features if f != feature]

            for value in X[feature].unique():
                mask = X[feature].to_numpy() == value
                node["children"][value] = self._build(X[mask], y[mask], new_features)

        return node

    def fit(self, X, y):
        self.tree = self._build(X.reset_index(drop=True), np.array(y), list(X.columns))

    def _predict_one(self, row, node):
        if "feature" not in node:
            return node["prediction"]

        feature = node["feature"]

        if node["type"] == "numeric":
            if row[feature] <= node["threshold"]:
                return self._predict_one(row, node["left"])

            return self._predict_one(row, node["right"])

        value = row[feature]

        if value not in node["children"]:
            return node["prediction"]

        return self._predict_one(row, node["children"][value])

    def predict(self, X):
        return np.array([self._predict_one(row, self.tree) for _, row in X.iterrows()])


def classify(train, test, criterion="information_gain", train_fraction=1.0):
    if not 0 < train_fraction <= 1:
        raise ValueError("train_fraction должен быть от 0 до 1")

    if train_fraction < 1:
        train = train.sample(frac=train_fraction, random_state=42)

    train = train.fillna("?")
    test = test.fillna("?")

    X_train = train.drop(columns="income")
    y_train = train["income"]

    X_test = test.drop(columns="income")
    y_test = test["income"]

    model = DecisionTree(criterion)
    model.fit(X_train, y_train)

    y_pred = model.predict(X_test)

    results = {
        "Accuracy (аккуратность):": accuracy_score(y_test, y_pred),
        "Precision (точность):": precision_score(y_test, y_pred, pos_label=">50K", zero_division=0),
        "Recall (полнота):": recall_score(y_test, y_pred, pos_label=">50K", zero_division=0),
        "F-мера:": f1_score(y_test, y_pred, pos_label=">50K", zero_division=0)
    }

    return model, results

